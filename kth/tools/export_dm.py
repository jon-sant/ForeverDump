import os as _wos  # portable root (handoff): WOWDEV_ROOT or the nearest parent dir holding foreverdump/
def _wowdev_root():
    r = _wos.environ.get("WOWDEV_ROOT")
    if r:
        return r
    d = _wos.path.dirname(_wos.path.abspath(__file__))
    while d != _wos.path.dirname(d) and not _wos.path.isdir(_wos.path.join(d, "foreverdump")):
        d = _wos.path.dirname(d)
    return d
_WROOT = _wowdev_root()
"""forever.5: export the C_DamageMeter snapshots recorded by ForeverDump (SV ForeverDumpCombatLogDB, damageMeter node,
taken on PLAYER_REGEN_ENABLED with GetCombatSessionFromType(Current, type)) into tests/replay/<run>.dm.lua.
Values are copied exactly as FD stored them: "<secret>" is FD's marker for a value that was secret when read and stays
as that literal string (the replay harness turns it back into a secret). Only the HealingDone and DamageDone sessions
are exported (the two the addon reads); nothing else is changed. Source: tools/dm_extract.lua -> kth/dm/<run>.dm.jsonl"""
import json, sys, subprocess, os
KEEP = ('HealingDone', 'DamageDone')
def lua(v, ind=''):
    if v is None: return 'nil'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, str): return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list): return '{' + ','.join(lua(x) for x in v) + '}'
    if isinstance(v, dict):
        return '{' + ','.join(('%s=%s' % (k, lua(x))) if k.isidentifier() else ('[%s]=%s' % (json.dumps(k, ensure_ascii=False), lua(x))) for k, x in v.items()) + '}'
    raise TypeError(v)
for run in sys.argv[1:]:
    sv = f'{_WROOT}/foreverdump/real/{run}/sv/ForeverDump.lua'
    jl = f'{_WROOT}/kth/dm/{run}.dm.jsonl'
    subprocess.run(['lua5.1', _WROOT + '/kth/tools/dm_extract.lua', sv], stdout=open(jl, 'w'), check=True)
    snaps = [json.loads(l) for l in open(jl)]
    snaps.sort(key=lambda s: s['gameTime'])
    out = [f'-- generated by tools/export_dm.py from {_wos.path.relpath(sv, _WROOT)} (ForeverDumpCombatLogDB damageMeter snapshots, raw values;',
           '-- "<secret>" = value was secret when FD read it). FD keeps the last 21 snapshots only (ring), so the early match',
           '-- has no snapshot: that is missing data, not zero healing.',
           'return {', f' meta = {{ run = "{run}", source = "ForeverDump SV damageMeter", n = {len(snaps)} }},', ' snaps = {']
    for s in snaps:
        bt = {k: s['byType'][k] for k in KEEP if k in s['byType']}
        out.append('  ' + lua({'g': s['gameTime'], 'time': s.get('time'), 'reason': s.get('reason'), 'inCombat': s.get('inCombat'), 'byType': bt}) + ',')
    out += [' },', '}']
    open(f'{_WROOT}/kth/tests/replay/{run}.dm.lua', 'w').write('\n'.join(out) + '\n')
    print(run, len(snaps), os.path.getsize(f'{_WROOT}/kth/tests/replay/{run}.dm.lua'))
