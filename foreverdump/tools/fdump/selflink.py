"""v2.2.16 self-link seed: per own spellID, how often my successful cast was followed by an aura on me in the same
frame (casts, hits). Gathered by the HSM replay of earlier captures (live-observable signals only: own cast success +
UNIT_AURA add on player), shipped as Data/SelfLinkSeed.lua and fed to the replay as `linkseed` events.
Spell IDs and counts only."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.join(HERE, "data", "selflink-seed.json")
LUA_PATH = os.path.join(HERE, "..", "..", "ForeverDump", "Data", "SelfLinkSeed.lua")


def merge(*stats):
    out = {}
    for st in stats:
        for k, v in (st or {}).items():
            a = out.setdefault(str(int(k)), {"casts": 0, "hits": 0})
            a["casts"] += int(v.get("casts", 0))
            a["hits"] += int(v.get("hits", 0))
    return out


def write(stats, generated, json_path=JSON_PATH, lua_path=LUA_PATH):
    stats = {k: v for k, v in stats.items() if v["casts"] > 0}
    with open(json_path, "w") as f:
        json.dump({"schema": "foreverdump.selflink/1", "generated": generated, "spells": stats}, f, indent=1, sort_keys=True)
    lines = ["-- ForeverDump self-link seed (generated by tools/fdump/selflink.py; JSON mirror tools/fdump/data/selflink-seed.json).",
             "-- Per own spellID: { casts, hits } = successful casts, and casts followed by an aura add on me in the same frame.",
             "-- Spell IDs and counts only. Loaded below live counts (Inference.SeedSelfLink); a link needs >= 4 casts, >= 60% hits.",
             "local _, ns = ...",
             "ns.SelfLinkSeed = {",
             '    schema = "foreverdump.selflink/1",',
             '    generated = "%s",' % generated,
             "    spells = {"]
    for k in sorted(stats, key=int):
        lines.append("        [%d] = { %d, %d }," % (int(k), stats[k]["casts"], stats[k]["hits"]))
    lines += ["    },", "}", ""]
    with open(lua_path, "w") as f:
        f.write("\n".join(lines))
    return len(stats)


def load(json_path=JSON_PATH):
    try:
        with open(json_path) as f:
            return json.load(f).get("spells", {})
    except (OSError, ValueError):
        return {}


def stream_events(t0, stats=None):
    stats = load() if stats is None else stats
    return [{"t": t0, "k": "linkseed", "spell": int(k), "casts": v["casts"], "hits": v["hits"]} for k, v in stats.items()]
