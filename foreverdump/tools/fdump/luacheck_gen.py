"""(3) luacheck config: a self-contained .luacheckrc defining std "forever"."""
import re

from .luasv import as_list
from .luals import lua_str

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_STD = {"_G", "assert", "collectgarbage", "error", "getfenv", "getmetatable", "ipairs", "load", "loadstring",
           "next", "pairs", "pcall", "print", "rawequal", "rawget", "rawset", "select", "setfenv",
           "setmetatable", "tonumber", "tostring", "type", "unpack", "xpcall", "coroutine", "debug", "io", "math",
           "os", "package", "string", "table", "module", "require", "dofile", "loadfile", "gcinfo", "newproxy", "arg"}
# Globals addons legitimately write into (fields only).
WRITABLE_TABLES = ("SlashCmdList", "StaticPopupDialogs", "UISpecialFrames", "UIPanelWindows", "BINDING_HEADER",
                   "hash_SlashCmdList", "ChatTypeInfo", "UnitPopupMenus")


def _fields(names):
    return "{ fields = { %s } }" % ", ".join(lua_str(n) for n in sorted(names))


def generate(dump, std_name="forever", extra_globals=()):
    ro = {}  # name -> lua expr
    for ns, info in dump.namespaces().items():
        fns = [f for f in as_list(info.get("functions")) if IDENT.match(str(f))]
        children = [c for c in (info.get("children") or {}) if IDENT.match(str(c))]
        fields_ = [lua_str(f) for f in sorted(set(fns) | set(as_list(list((info.get("fields") or {}).keys()))))]
        for c in sorted(children):
            fields_.append("%s = { other_fields = true }" % c)
        ro[ns] = "{ fields = { %s } }" % ", ".join(fields_)
    secure, insecure = dump.global_functions()
    for f in secure:
        if IDENT.match(f):
            ro.setdefault(f, "{}")
    enum = dump.runtime_enum()
    if enum:
        ro["Enum"] = "{ fields = { %s } }" % ", ".join(
            "%s = %s" % (k, _fields(v.keys()) if isinstance(v, dict) else "{}") for k, v in sorted(enum.items()) if IDENT.match(str(k)))
    else:
        ro["Enum"] = "{ other_fields = true }"
    ro["Constants"] = "{ other_fields = true }"
    for name, info in dump.global_tables().items():
        if IDENT.match(name) and name not in LUA_STD and not str(name).startswith("ForeverDump") and name not in ro:
            ro[name] = "{ other_fields = true }"
    for name in dump.frames():
        if IDENT.match(name) and name not in ro:
            ro[name] = "{ other_fields = true }"
    for name in list(dump.constants().keys()) + list(dump.strings.keys()):
        if IDENT.match(str(name)):
            ro.setdefault(name, "{}")
    for name in ("CreateFrame", "hooksecurefunc", "issecretvalue", "issecrettable", "canaccessvalue",
                 "securecall", "issecure", "GetTime", "date", "time", "strsplit", "strjoin", "strtrim",
                 "tinsert", "tremove", "wipe", "format", "strmatch", "strfind", "gsub", "strlower", "strupper",
                 "floor", "ceil", "max", "min", "abs", "sort", "bit", "debugstack", "geterrorhandler",
                 "seterrorhandler", "debugprofilestop", "tContains", "Mixin", "CreateFromMixins"):
        if name in dump.all_global_names():
            ro.setdefault(name, "{}")
    for t in WRITABLE_TABLES:
        ro.pop(t, None)
    lines = ["-- Generated by ForeverDump tools from %s." % dump.build_label(),
             "-- Usage: copy as .luacheckrc (or merge the stds block into yours) and run `luacheck <addon>`.",
             "stds = stds or {}",
             "stds.%s = {" % std_name,
             "\tread_globals = {"]
    for name in sorted(ro):
        lines.append("\t\t%s = %s," % (name, ro[name]))
    lines.append("\t},")
    lines.append("\tglobals = {")
    for t in WRITABLE_TABLES:
        if t in dump.all_global_names() or t in ("SlashCmdList", "StaticPopupDialogs", "UISpecialFrames"):
            lines.append("\t\t%s = { other_fields = true }," % t)
    for g in extra_globals:
        lines.append("\t\t%s = {}," % lua_str(g))
    lines.append("\t},")
    lines.append("}")
    lines.append('std = "lua51+%s"' % std_name)
    lines.append("max_line_length = false")
    lines.append('-- Your addon\'s own globals (SavedVariables, SLASH_* names) go here:')
    lines.append("-- globals = { \"MyAddonDB\", \"SLASH_MYADDON1\" }")
    lines.append('ignore = { "212/self" }')
    return "\n".join(lines) + "\n"
